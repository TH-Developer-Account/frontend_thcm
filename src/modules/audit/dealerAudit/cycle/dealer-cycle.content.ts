/** Replaces {tokens} in a message. Unknown tokens are left as-is. */
export const formatCycleMessage = (
	template: string,
	values: Record<string, string | number>,
): string =>
	template.replace(/\{(\w+)\}/g, (match, key: string) =>
		key in values ? String(values[key]) : match,
	);
